import { TANK_CLEANING_QUALIFICATIONS, workStatus, type Contract, type ContractObject, type DeadlineEdit, type WorkItem, type WorkUnit } from '../../shared.js'

/**
 * Completed volumes of started works are what the daily reports add up to (see `reports.ts`):
 * every work with an actual start gets a report on each of its working days.
 */
type WorkSeed = [
  id: string,
  title: string,
  unit: WorkUnit,
  plannedVolume: number,
  actualVolume: number,
  plannedStart: string,
  plannedEnd: string,
  actualStart?: string,
  actualEnd?: string,
]

function works(list: WorkSeed[]): WorkItem[] {
  return list.map(([id, title, unit, plannedVolume, actualVolume, plannedStart, plannedEnd, actualStart, actualEnd]) => ({
    id,
    title,
    unit,
    plannedVolume,
    actualVolume,
    plannedStart,
    plannedEnd,
    ...(actualStart ? { actualStart } : {}),
    ...(actualEnd ? { actualEnd } : {}),
    status: workStatus({ actualStart, actualEnd }),
  }))
}

function object(
  id: string,
  name: string,
  location: string,
  [plannedStart, plannedEnd]: [string, string],
  [actualStart, actualEnd]: [string?, string?],
  list: WorkSeed[],
  deadlineEdits: DeadlineEdit[] = [],
): ContractObject {
  const taskId = actualStart && !actualEnd ? String(1000 + Number(id.replace(/\D/g, '') || 0)) : undefined
  return {
    id,
    name,
    location,
    plannedStart,
    plannedEnd,
    ...(actualStart ? { actualStart } : {}),
    ...(actualEnd ? { actualEnd } : {}),
    works: works(list),
    deadlineEdits,
    requiredQualificationIds: [...TANK_CLEANING_QUALIFICATIONS],
    ...(taskId ? { bitrixTaskId: taskId, bitrixTaskTitle: name } : {}),
  }
}

