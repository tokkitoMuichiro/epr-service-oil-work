import { TANK_CLEANING_QUALIFICATIONS, workStatus, type Contract, type ContractObject, type WorkItem, type WorkUnit } from '../../shared.js'

type WorkSeed = [
  id: string,
  title: string,
  unit: WorkUnit,
  plannedVolume: number,
  actualVolume: number,
  plannedStart: string,
  plannedEnd: string,
  actualStart?: string,
  actualEnd?: string,
]

function works(list: WorkSeed[]): WorkItem[] {
  return list.map(([id, title, unit, plannedVolume, actualVolume, plannedStart, plannedEnd, actualStart, actualEnd]) => ({
    id,
    title,
    unit,
    plannedVolume,
    actualVolume,
    plannedStart,
    plannedEnd,
    ...(actualStart ? { actualStart } : {}),
    ...(actualEnd ? { actualEnd } : {}),
    status: workStatus({ actualStart, actualEnd }),
  }))
}

function object(
  id: string,
  name: string,
  location: string,
  [plannedStart, plannedEnd]: [string, string],
  [actualStart, actualEnd]: [string?, string?],
  list: WorkSeed[],
): ContractObject {
  return {
    id,
    name,
    location,
    plannedStart,
    plannedEnd,
    ...(actualStart ? { actualStart } : {}),
    ...(actualEnd ? { actualEnd } : {}),
    works: works(list),
    deadlineEdits: [],
  }
}

export function contractsSeed(): Contract[] {
  return demoContracts().map((contract) => ({
    ...contract,
    objects: contract.objects.map((o) => ({ ...o, requiredQualificationIds: [...TANK_CLEANING_QUALIFICATIONS] })),
  }))
}

